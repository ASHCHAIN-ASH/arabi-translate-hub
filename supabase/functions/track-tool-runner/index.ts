Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const auth = req.headers.get("Authorization");
    if (!auth) return json({ error: "غير مصرح" }, 401);

    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) return json({ error: "AI key missing" }, 500);

    const supabase = createClient(
      Deno.env.get("SUPABASE_URL")!,
      Deno.env.get("SUPABASE_ANON_KEY")!,
      { global: { headers: { Authorization: auth } } }
    );
    const { data: u } = await supabase.auth.getUser();
    if (!u?.user) return json({ error: "غير مصرح" }, 401);

    const { tool_slug, input, options, mode } = await req.json();
    if (!tool_slug || !PROMPTS[tool_slug]) {
      return json({ error: `أداة غير مدعومة: ${tool_slug}` }, 400);
    }
    if (!input || typeof input !== "string") {
      return json({ error: "المُدخل مفقود" }, 400);
    }

    const cfg = PROMPTS[tool_slug];
    const trimmed = input.trim();
    if (trimmed.length < cfg.minLen) {
      return json({ error: `المُدخل قصير (الحد ${cfg.minLen} حرف)` }, 400);
    }
    if (trimmed.length > cfg.maxLen) {
      return json({ error: `المُدخل طويل (الحد ${cfg.maxLen} حرف)` }, 400);
    }

    const isPro = mode === "pro";
    const model = isPro ? "google/gemini-2.5-pro" : "google/gemini-2.5-flash";

    const r = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model,
        messages: [
          { role: "system", content: cfg.system },
          { role: "user", content: cfg.userTpl(trimmed, options || {}) },
        ],
      }),
    });

    if (r.status === 429) return json({ error: "تم تجاوز الحد، حاول لاحقاً" }, 429);
    if (r.status === 402) return json({ error: "نفدت أرصدة الذكاء الاصطناعي" }, 402);
    if (!r.ok) {
      const t = await r.text();
      console.error("AI error", r.status, t);
      return json({ error: "فشل الاتصال بالذكاء الاصطناعي" }, 500);
    }

    const data = await r.json();
    const content = data?.choices?.[0]?.message?.content || "";
    return json({ ok: true, result: content, mode: isPro ? "pro" : "standard" });
  } catch (e) {
    console.error("track-tool-runner error:", e);
    return json({ error: e instanceof Error ? e.message : "خطأ غير متوقع" }, 500);
  }
});

function json(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, "Content-Type": "application/json" },
  });
}
