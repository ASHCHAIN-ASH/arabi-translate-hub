export interface LegalTemplateContext {
  contractNumber: string;
  serviceName: string;
  serviceDescription?: string;
  clientFullName: string;
  clientIdNumber?: string;
  clientEmail?: string;
  clientPhone?: string;
  clientCompany?: string;
  totalAmount: number;
  currency?: string;
  paymentTerms?: string;
  deliveryDate?: string;
  workDuration?: string;
  issueDate: string;
  templateType?: ContractTemplateType;
  // اختياري: مخرجات وجدول مراحل قابل للتمرير لتفاصيل أعمق
  deliverables?: string[];
  paymentSchedule?: Array<{ stage: string; percent: number; due: string }>;
  scopeItems?: Array<{ item: string; details: string }>;
}

const fmtMoney = (n: number, c: string = "SAR") =>
  new Intl.NumberFormat("ar-SA", { style: "currency", currency: c, maximumFractionDigits: 2 }).format(n || 0);

const fmtDate = (d?: string) => {
  if (!d) return "—";
  try {
    return new Date(d).toLocaleDateString("ar-SA", { year: "numeric", month: "long", day: "numeric" });
  } catch {
    return d;
  }
};

