function clientBlock(ctx: LegalTemplateContext): string {
  const lines = [`الاسم الكامل: ${ctx.clientFullName}`];
  if (ctx.clientIdNumber) lines.push(`رقم الهوية الوطنية / الإقامة: ${ctx.clientIdNumber}`);
  if (ctx.clientCompany) lines.push(`جهة العمل / الشركة: ${ctx.clientCompany}`);
  if (ctx.clientEmail) lines.push(`البريد الإلكتروني الرسمي للتبليغ: ${ctx.clientEmail}`);
  if (ctx.clientPhone) lines.push(`رقم الجوال للتواصل: ${ctx.clientPhone}`);
  return lines.join("\n");
}

function scopeTable(ctx: LegalTemplateContext): string {
  const items = ctx.scopeItems && ctx.scopeItems.length
    ? ctx.scopeItems
    : [
      { item: "اسم الخدمة", details: ctx.serviceName },
      ...(ctx.serviceDescription ? [{ item: "الوصف التفصيلي", details: ctx.serviceDescription }] : []),
      { item: "القيمة الإجمالية", details: fmtMoney(ctx.totalAmount, ctx.currency || "SAR") },
      ...(ctx.paymentTerms ? [{ item: "شروط الدفع", details: ctx.paymentTerms }] : []),
      ...(ctx.workDuration ? [{ item: "مدة التنفيذ", details: ctx.workDuration }] : []),
      ...(ctx.deliveryDate ? [{ item: "موعد التسليم", details: fmtDate(ctx.deliveryDate) }] : []),
    ];

  // يُحوَّل لاحقاً إلى جدول HTML داخل عارض العقد. صياغة Markdown قياسية.
  let table = "| البند | التفاصيل |\n|---|---|\n";
  for (const r of items) {
    const safe = (s: string) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
    table += `| ${safe(r.item)} | ${safe(r.details)} |\n`;
  }
  return table;
}

function paymentScheduleTable(ctx: LegalTemplateContext): string {
  if (!ctx.paymentSchedule || ctx.paymentSchedule.length === 0) return "";
  let table = "| المرحلة | النسبة | الاستحقاق |\n|---|---|---|\n";
  for (const p of ctx.paymentSchedule) {
    table += `| ${p.stage} | ${p.percent}% | ${p.due} |\n`;
  }
  return table;
}

function deliverablesList(ctx: LegalTemplateContext): string {
  if (!ctx.deliverables || ctx.deliverables.length === 0) return "";
  return ctx.deliverables.map((d, i) => `${i + 1}. ${d}`).join("\n");
}

