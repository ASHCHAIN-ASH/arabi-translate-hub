function buildCorporateContract(ctx: LegalTemplateContext): string {
  const intro = `حيث إن **${PARENT_COMPANY.platformName}** تعمل في تقديم خدمات احترافية للشركات والمؤسسات وفق أعلى المعايير، ورغبةً من الشركة الموقّعة أدناه في إبرام شراكة مهنية للحصول على الخدمات/التوريدات المُبيّنة؛ فقد اتفق الطرفان على إبرام هذا العقد التجاري الملزم وفق البنود الآتية:`;

  const companyBlock = ctx.clientCompany
    ? `الكيان القانوني: **${ctx.clientCompany}**\nممثَّلاً بـ: ${ctx.clientFullName}${ctx.clientIdNumber ? ` (هوية: ${ctx.clientIdNumber})` : ""}\n${ctx.clientEmail ? `البريد الإلكتروني الرسمي: ${ctx.clientEmail}\n` : ""}${ctx.clientPhone ? `جوال التواصل: ${ctx.clientPhone}` : ""}`
    : clientBlock(ctx);

  return `
# عقد شراكة/توريد خدمات احترافية للشركات
### رقم العقد: ${ctx.contractNumber}
### تاريخ التحرير: ${fmtDate(ctx.issueDate)}
### نوع العقد: شراكة شركات (B2B Corporate Services Agreement)
### مكان الإبرام: ${PARENT_COMPANY.jurisdiction}

---

${partiesAndScope(ctx, "الطرف الثاني (الشركة المتعاقدة)", companyBlock, intro)}

## البند الأول: نطاق الشراكة والتوريد (Scope of Engagement)

${scopeTable(ctx)}

${ctx.deliverables?.length ? `**المخرجات والتوريدات:**\n${deliverablesList(ctx)}\n` : ""}

## البند الثاني: مستوى الخدمة (Service Level Agreement - SLA)
1. **زمن الاستجابة لطلبات الدعم:** خلال (4) ساعات عمل خلال أيام العمل الرسمية.
2. **زمن حل المشكلات الحرجة:** خلال (24) ساعة من الإبلاغ.
3. **توفر الخدمة:** لا يقل عن (99٪) خلال شهر تقويمي.
4. **التقارير الدورية:** تقرير أداء شهري مُفصَّل.
5. أي إخلال بمستوى الخدمة يستوجب حسماً من الفاتورة الشهرية بنسبة متفق عليها.

## البند الثالث: التزامات الطرف الأول (المُقدِّم)
1. تقديم الخدمات/التوريدات وفق المواصفات المتفق عليها بدقة تامة.
2. تخصيص فريق مؤهل ومدير حساب مخصص للشركة.
3. الالتزام بمعايير الجودة الدولية ISO 9001 (إن أمكن).
4. تقديم تأمين مهني (Professional Indemnity) إن طلبت الشركة ذلك.
5. الإخطار المسبق بأي تغيير في الفريق المُنفِّذ.

## البند الرابع: التزامات الطرف الثاني (الشركة)
1. تعيين منسّق رسمي مخوّل بالتواصل واتخاذ القرارات.
2. توفير المعلومات والوصول اللازمين خلال (3) أيام عمل من الطلب.
3. سداد الفواتير في المواعيد المُحدَّدة (صافي 30 يوماً ما لم يُتفق على غير ذلك).
4. عدم التعاقد المباشر مع موظفي الطرف الأول لمدة (24) شهراً بعد انتهاء العقد.

## البند الخامس: المقابل المالي والفوترة
1. القيمة الإجمالية: **${fmtMoney(ctx.totalAmount, ctx.currency || "SAR")}** (شامل ضريبة القيمة المضافة 15٪).
${ctx.paymentSchedule?.length ? `\n**جدول الدفع المرحلي:**\n${paymentScheduleTable(ctx)}\n` : ""}
2. تُصدَر الفواتير شهرياً، ويُستحق السداد خلال (30) يوماً من تاريخ الفاتورة.
3. التأخر في السداد يُعطي الحق في احتساب فائدة تأخير بنسبة (1.5٪) شهرياً.
4. التأخر لأكثر من (60) يوماً يُعطي الطرف الأول الحق في تعليق الخدمة بإشعار مسبق (7) أيام.

## البند السادس: ضمان الأداء وعقوبات الإخلال
1. يقدّم الطرف الأول ضمان حسن أداء بقيمة (5٪) من قيمة العقد عند الاتفاق على ذلك.
2. الإخلال الجسيم يُلزم الطرف المُخلّ بتعويض الطرف الآخر عن الأضرار المباشرة.
3. سقف التعويض الإجمالي: قيمة العقد المدفوعة خلال آخر (12) شهراً.

## البند السابع: السرية وحماية البيانات
1. اتفاقية عدم إفشاء (NDA) سارية لمدة (5) سنوات بعد انتهاء العقد.
2. الالتزام بـ **نظام حماية البيانات الشخصية** السعودي ولوائح **هيئة الاتصالات والفضاء والتقنية**.
3. حماية بيانات الشركة بإجراءات تشفير وأمن سيبراني معتمدة.
4. الإبلاغ الفوري عن أي حادث أمني خلال (24) ساعة من اكتشافه.

## البند الثامن: الملكية الفكرية
1. **مخرجات مخصصة للشركة:** تنتقل ملكيتها للشركة بعد السداد الكامل.
2. **أدوات وقوالب وتقنيات الطرف الأول:** تظل ملكاً حصرياً له، مع منح الشركة رخصة استخدام محدودة.
3. **التحسينات المشتركة:** تُحدَّد ملكيتها كتابياً قبل بدء التطوير.

## البند التاسع: مدة العقد والتجديد
${ctx.workDuration ? `1. **مدة العقد:** ${ctx.workDuration} من تاريخ التوقيع.\n` : "1. **مدة العقد:** سنة واحدة من تاريخ التوقيع.\n"}
2. يُجدَّد العقد تلقائياً لمدد مماثلة ما لم يُخطر أحد الطرفين الآخر بعدم الرغبة قبل (60) يوماً من انتهاء المدة.
3. لأي طرف الحق في الإنهاء المبكر بإشعار مسبق (90) يوماً مع تسوية المستحقات.

## البند العاشر: القوة القاهرة
1. تشمل: الكوارث الطبيعية، الأوبئة، الحروب، الإضرابات العامة، انقطاع الخدمات الحكومية.
2. الإخطار المتبادل خلال (48) ساعة.
3. استمرارها لأكثر من (60) يوماً يُعطي حق الفسخ دون مسؤولية.

## البند الحادي عشر: التبليغات
عبر البريد الإلكتروني الرسمي للشركة، أو خطاب رسمي بالبريد المسجَّل، وتُعدّ نافذة بعد (48) ساعة من إرسالها.

${commonClosing(ctx.clientFullName)}
`.trim();
}

